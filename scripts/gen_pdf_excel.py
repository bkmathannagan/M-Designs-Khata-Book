w('app/src/main/java/com/mdesigns/khata/core/pdf/PdfReportGenerator.kt', '''
package com.mdesigns.khata.core.pdf

import android.content.Context
import android.graphics.Canvas
import android.graphics.Color
import android.graphics.Paint
import android.graphics.pdf.PdfDocument
import com.mdesigns.khata.core.utils.CurrencyFormatter
import com.mdesigns.khata.core.utils.DateUtils
import java.io.File
import java.io.FileOutputStream

object PdfReportGenerator {

    data class ReportItem(
        val date: Long,
        val description: String,
        val debit: Double,
        val credit: Double,
        val runningBalance: Double
    )

    data class ReportData(
        val businessName: String,
        val businessPhone: String,
        val personName: String,
        val personPhone: String,
        val openingBalance: Double,
        val isOpeningDebit: Boolean,
        val items: List<ReportItem>,
        val totalDebit: Double,
        val totalCredit: Double,
        val closingBalance: Double
    )

    fun generatePersonStatement(context: Context, data: ReportData): File {
        val pdfDocument = PdfDocument()
        val pageInfo = PdfDocument.PageInfo.Builder(595, 842, 1).create()
        val page = pdfDocument.startPage(pageInfo)
        val canvas: Canvas = page.canvas

        val paint = Paint().apply { isAntiAlias = true }

        // Header Banner
        paint.color = Color.rgb(0, 106, 96)
        canvas.drawRect(0f, 0f, 595f, 90f, paint)

        // Header Title
        paint.color = Color.WHITE
        paint.textSize = 20f
        paint.isFakeBoldText = true
        canvas.drawText("M DESIGNS KHATA", 30f, 40f, paint)

        paint.textSize = 12f
        paint.isFakeBoldText = false
        canvas.drawText("Digital Ledger Statement | https://mdesignsrmd.com", 30f, 65f, paint)

        // Business & Person Info
        paint.color = Color.DKGRAY
        paint.textSize = 12f
        paint.isFakeBoldText = true
        canvas.drawText("Business: ${data.businessName} (${data.businessPhone})", 30f, 120f, paint)
        canvas.drawText("Customer / Party: ${data.personName} (${data.personPhone})", 30f, 140f, paint)
        canvas.drawText("Date Generated: ${DateUtils.formatDateTime(System.currentTimeMillis())}", 30f, 160f, paint)

        val opDirection = if (data.isOpeningDebit) "You Collect" else "You Give"
        canvas.drawText("Opening Balance: ${CurrencyFormatter.format(data.openingBalance)} ($opDirection)", 30f, 180f, paint)

        // Table Header
        paint.color = Color.rgb(230, 240, 238)
        canvas.drawRect(30f, 200f, 565f, 225f, paint)

        paint.color = Color.BLACK
        paint.textSize = 10f
        paint.isFakeBoldText = true
        canvas.drawText("Date", 35f, 217f, paint)
        canvas.drawText("Description", 110f, 217f, paint)
        canvas.drawText("Debit (Give)", 290f, 217f, paint)
        canvas.drawText("Credit (Receive)", 385f, 217f, paint)
        canvas.drawText("Balance", 490f, 217f, paint)

        // Table Rows
        var y = 245f
        paint.isFakeBoldText = false
        for (item in data.items.take(25)) {
            canvas.drawText(DateUtils.formatDate(item.date), 35f, y, paint)
            val desc = if (item.description.length > 22) item.description.take(20) + ".." else item.description
            canvas.drawText(desc, 110f, y, paint)
            canvas.drawText(if (item.debit > 0) CurrencyFormatter.format(item.debit) else "-", 290f, y, paint)
            canvas.drawText(if (item.credit > 0) CurrencyFormatter.format(item.credit) else "-", 385f, y, paint)
            canvas.drawText(CurrencyFormatter.format(item.runningBalance), 490f, y, paint)
            y += 20f
        }

        // Summary Box
        paint.color = Color.rgb(240, 240, 240)
        canvas.drawRect(30f, y + 10f, 565f, y + 70f, paint)

        paint.color = Color.BLACK
        paint.isFakeBoldText = true
        paint.textSize = 11f
        canvas.drawText("Total Debit (Give): ${CurrencyFormatter.format(data.totalDebit)}", 40f, y + 35f, paint)
        canvas.drawText("Total Credit (Receive): ${CurrencyFormatter.format(data.totalCredit)}", 40f, y + 55f, paint)

        val finalDir = if (data.closingBalance >= 0) "You Collect" else "You Give"
        canvas.drawText("Net Closing Balance: ${CurrencyFormatter.format(data.closingBalance)} ($finalDir)", 300f, y + 45f, paint)

        // Footer
        paint.textSize = 9f
        paint.isFakeBoldText = false
        paint.color = Color.GRAY
        canvas.drawText("Generated by M Designs Khata © M Designs (https://mdesignsrmd.com)", 130f, 820f, paint)

        pdfDocument.finishPage(page)

        val outputDir = File(context.cacheDir, "reports").apply { mkdirs() }
        val file = File(outputDir, "Statement_${System.currentTimeMillis()}.pdf")
        val fos = FileOutputStream(file)
        pdfDocument.writeTo(fos)
        pdfDocument.close()
        fos.close()

        return file
    }
}
''')

